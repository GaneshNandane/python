# Simple program to demonstrate the use of the capitalize() method

# Define a string with all lowercase letters
str1 = "hello"

# Capitalize the first character of the string
# The capitalize() method converts the first character to uppercase
# and converts the remaining characters to lowercase
capstr1 = str1.capitalize()

# Print the capitalized string
print(capstr1)


# Define a string containing both lowercase and uppercase letters
str2 = "hello worlD"

# Capitalize the first character and convert the remaining characters to lowercase
capstr2 = str2.capitalize()

# Print the capitalized string
print(capstr2)
