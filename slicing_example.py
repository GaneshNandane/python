# simple program for string slicing

# defining a string
pie="ApplePie"

# printing five index from strart
print(pie[:5])      #Slicing fron start

# printing rest of the index from 5th index
print(pie[5:])      #Slicing till End

# printing index between 2 to six
print(pie[2:6])     #Slicing in between

# printing using negative indexing 
print(pie[-8:])     #Slicing using negative index
