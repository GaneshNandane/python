# iterating over a list elements using for loop 
# for list iterabel 
l = [2, 4, 34, "sgdd", 243,]
for i in l:
    print(i)

# iterating over a tuple elements using for loop 
# for tuple iterable 
t = (3, 434, 5, "#445", "dgh", 34)  
for i in t:
    print(i)  
    
# iterating over a string elements using for loop 
# for string iterable  
s = "Ganesh Harichandra Nandane"
for i in s:
    print(i)
