# simple program to sort the list in reversed order

# defining the list of elements
colors=["Voilet", "Indigo", "Blue", "Green"]

# sorting the list of elements in reversed order from Z-to-A
colors.sort(reverse=True)

# printinig the reversed sorted list
print(colors)

# defining a list of numbers
num=[4, 2, 5, 3, 6, 1, 2, 1, 2, 8, 9, 7]

# sorting the list of numbers in reversed order from 9-to-1
num.sort(reverse=True)

# printing the reversed sorted list
print(num)
