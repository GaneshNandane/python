# this is the simple example of the tuple negative indexing
# Note: negative indexing always starts with -1 

country=("Spain", "Italy", "India", "England", "Germany",)
#         ["-5"     "-4"     "-3"      "-2"       "-1"]
print(country[-1])
print(country[-2])
print(country[-3])
print(country[-4])
print(country[-5])
