# Simple program to check whether all characters in a string are whitespace

# Define a string containing one space
str1 = " "

# Check whether all characters in the string are whitespace
print(str1.isspace())  # Using the Spacebar


# Define a string containing two spaces
str2 = "  "

# Check whether all characters in the string are whitespace
print(str2.isspace())  # Using the Spacebar
